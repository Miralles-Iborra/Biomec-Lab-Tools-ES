def emparejar_sesion(
    sesion_rpe,
    sesiones_hrv,
    hojas_usadas,
    modo,
    permitir_fallback,
):
    disponibles = [
        sesion
        for sesion in sesiones_hrv
        if sesion["hoja"] not in hojas_usadas
    ]

    if modo in {
        "Fecha exacta",
        "Automático",
    }:

        candidatos = [
            sesion
            for sesion in disponibles
            if (
                sesion["fecha"]
                == sesion_rpe["fecha"]
            )
        ]

        if len(candidatos) == 1:
            return (
                candidatos[0],
                "fecha",
                "",
            )

        if (
            modo == "Fecha exacta"
            or not permitir_fallback
        ):
            return (
                None,
                "fecha",
                "No existe una hoja HRV "
                "con la misma fecha.",
            )

    if modo in {
        "Orden de las hojas",
        "Automático",
    }:

        if disponibles:

            sesion_hrv = disponibles[0]
            aviso = ""

            if (
                sesion_hrv["fecha"]
                != sesion_rpe["fecha"]
            ):
                aviso = (
                    "Emparejada por orden pese "
                    "a fechas distintas: "
                    f"RPE {sesion_rpe['fecha']} / "
                    f"HRV {sesion_hrv['fecha']}."
                )

            return (
                sesion_hrv,
                "orden",
                aviso,
            )

    return (
        None,
        modo,
        "No se pudo emparejar la sesión.",
    )


