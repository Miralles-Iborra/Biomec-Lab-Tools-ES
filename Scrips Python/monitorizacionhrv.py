def leer_valoracion_rpe(
    ruta,
    hoja_rpe,
    sujeto,
):
    """
    Extrae HRMAX50, HRMAX75, RPE e intervalos de cada sesión.
    """
    datos_rpe = pd.read_excel(
        ruta,
        sheet_name=hoja_rpe,
        dtype=object,
    )

    columnas = {
        normalizar(columna): columna
        for columna
        in datos_rpe.columns
    }

    columna_sujeto = columnas.get(
        "SUJETO"
    )

    if columna_sujeto is None:
        raise ValueError(
            "No existe la columna SUJETO "
            "en la hoja RPE."
        )

    seleccion = datos_rpe[
        datos_rpe[columna_sujeto]
        .astype(str)
        .str.strip()
        .str.upper()
        == sujeto.strip().upper()
    ]

    if seleccion.empty:

        sujetos_disponibles = sorted(
            datos_rpe[columna_sujeto]
            .dropna()
            .astype(str)
            .str.strip()
            .unique()
            .tolist()
        )

        raise ValueError(
            f"No se encontró el sujeto {sujeto}. "
            f"Sujetos disponibles: "
            f"{sujetos_disponibles}"
        )

    fila = seleccion.iloc[0]

    hrmax50 = pd.to_numeric(
        obtener_valor(
            fila,
            columnas,
            "HRMAX50",
        ),
        errors="coerce",
    )

    hrmax75 = pd.to_numeric(
        obtener_valor(
            fila,
            columnas,
            "HRMAX75",
        ),
        errors="coerce",
    )

    if (
        pd.isna(hrmax50)
        or pd.isna(hrmax75)
    ):
        raise ValueError(
            "HRMAX50 y HRMAX75 deben "
            "contener valores numéricos."
        )

    numeros_sesion = sorted(
        {
            int(coincidencia.group(1))
            for columna
            in datos_rpe.columns
            if (
                coincidencia
                := re.fullmatch(
                    r"SESION(\d+)",
                    normalizar(columna),
                )
            )
        }
    )

    sesiones = []

    for numero in numeros_sesion:

        fecha = convertir_fecha(
            obtener_valor(
                fila,
                columnas,
                f"SESION{numero}",
            )
        )

        if fecha is None:
            continue

        sesiones.append(
            {
                "numero": numero,
                "fecha": fecha,

                "FUERZA": {
                    "rpe": obtener_valor(
                        fila,
                        columnas,
                        f"RPE_FUERZA_SESION{numero}",
                    ),
                    "inicio": convertir_a_segundos(
                        obtener_valor(
                            fila,
                            columnas,
                            f"TIEMPOini_FUERZA_SESION{numero}",
                        )
                    ),
                    "fin": convertir_a_segundos(
                        obtener_valor(
                            fila,
                            columnas,
                            f"TIEMPOFIN_FUERZA_SESION{numero}",
                        )
                    ),
                },

                "FUNCIONAL": {
                    "rpe": obtener_valor(
                        fila,
                        columnas,
                        f"RPE_FUNCIONAL_SESION{numero}",
                    ),
                    "inicio": convertir_a_segundos(
                        obtener_valor(
                            fila,
                            columnas,
                            f"TIEMPOini_FUNCIONAL_SESION{numero}",
                        )
                    ),
                    "fin": convertir_a_segundos(
                        obtener_valor(
                            fila,
                            columnas,
                            f"TIEMPOFIN_FUNCIONAL_SESION{numero}",
                        )
                    ),
                },

                "RESISTENCIA": {
                    "rpe": obtener_valor(
                        fila,
                        columnas,
                        f"RPE_RESIST_SESION{numero}",
                        f"RPE_RESISTENCIA_SESION{numero}",
                    ),
                    "inicio": convertir_a_segundos(
                        obtener_valor(
                            fila,
                            columnas,
                            f"TIEMPOini_RESIT_SESION{numero}",
                            f"TIEMPOini_RESIST_SESION{numero}",
                            f"TIEMPOini_RESISTENCIA_SESION{numero}",
                        )
                    ),
                    "fin": convertir_a_segundos(
                        obtener_valor(
                            fila,
                            columnas,
                            f"TIEMPOFIN_RESIST_SESION{numero}",
                            f"TIEMPOFIN_RESISTENCIA_SESION{numero}",
                        )
                    ),
                },
            }
        )

    if not sesiones:
        raise ValueError(
            "No se encontraron sesiones "
            "con fecha en la hoja RPE."
        )

    return {
        "hrmax50": float(hrmax50),
        "hrmax75": float(hrmax75),
        "sesiones": sesiones,
    }


