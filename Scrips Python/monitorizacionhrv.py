def leer_hoja_hrv(
    ruta,
    hoja,
):
    """
    Lee una hoja del Excel de HRV.

    Devuelve:
    - fecha de la sesión;
    - tiempo en segundos;
    - frecuencia cardiaca;
    - periodo de muestreo;
    - inicio y final del registro.
    """

    datos_brutos = pd.read_excel(
        ruta,
        sheet_name=hoja,
        header=None,
        dtype=object,
    )

    if datos_brutos.empty:
        raise ValueError(
            f"La hoja {hoja} está vacía."
        )

    # ------------------------------------------------------------
    # Extraer metadatos de las dos primeras filas
    # ------------------------------------------------------------

    metadatos = {}

    if len(datos_brutos) >= 2:

        for encabezado, valor in zip(
            datos_brutos.iloc[0].tolist(),
            datos_brutos.iloc[1].tolist(),
        ):

            clave = normalizar(encabezado)

            if clave:
                metadatos[clave] = valor

    fecha = convertir_fecha(
        metadatos.get(
            "DATE",
            metadatos.get("FECHA"),
        )
    )

    # ------------------------------------------------------------
    # Localizar la fila que contiene Time y HR (bpm)
    # ------------------------------------------------------------

    fila_encabezado = None
    columna_tiempo = None
    columna_hr = None

    encabezados_tiempo = {
        "TIME",
        "TIEMPO",
        "ELAPSEDTIME",
        "DURATION",
    }

    encabezados_hr = {
        "HR",
        "HRBPM",
        "HEARTRATE",
        "HEARTRATEBPM",
        "FC",
        "FCBPM",
    }

    for numero_fila in range(
        min(20, len(datos_brutos))
    ):

        fila_normalizada = [
            normalizar(valor)
            for valor
            in datos_brutos.iloc[
                numero_fila
            ].tolist()
        ]

        columnas_tiempo = [
            posicion
            for posicion, valor
            in enumerate(fila_normalizada)
            if valor in encabezados_tiempo
        ]

        columnas_hr = [
            posicion
            for posicion, valor
            in enumerate(fila_normalizada)
            if valor in encabezados_hr
        ]

        if columnas_tiempo and columnas_hr:

            fila_encabezado = numero_fila
            columna_tiempo = columnas_tiempo[0]
            columna_hr = columnas_hr[0]

            break

    if fila_encabezado is None:

        raise ValueError(
            f"No se localizaron las columnas "
            f"Time y HR en la hoja {hoja}."
        )

    # ------------------------------------------------------------
    # Extraer únicamente tiempo y frecuencia cardiaca
    # ------------------------------------------------------------

    datos = datos_brutos.iloc[
        fila_encabezado + 1:,
        [
            columna_tiempo,
            columna_hr,
        ],
    ].copy()

    datos.columns = [
        "tiempo_original",
        "hr",
    ]

    # La columna Time contiene datetime.time, por lo que debe
    # convertirse elemento a elemento mediante convertir_a_segundos().
    datos["tiempo_s"] = datos[
        "tiempo_original"
    ].apply(
        convertir_a_segundos
    )

    datos["hr"] = pd.to_numeric(
        datos["hr"],
        errors="coerce",
    )

    datos = datos[
        [
            "tiempo_s",
            "hr",
        ]
    ].dropna()

    datos = (
        datos
        .sort_values("tiempo_s")
        .drop_duplicates(
            subset="tiempo_s",
            keep="first",
        )
        .reset_index(drop=True)
    )

    if datos.empty:

        raise ValueError(
            f"La hoja {hoja} no contiene "
            f"datos válidos de FC después "
            f"de convertir la columna Time."
        )

    datos["tiempo_s"] = (
        datos["tiempo_s"]
        .astype(float)
        .round(6)
    )

    # ------------------------------------------------------------
    # Calcular el periodo de muestreo
    # ------------------------------------------------------------

    diferencias = (
        datos["tiempo_s"]
        .diff()
    )

    diferencias = diferencias[
        diferencias > 0
    ]

    if len(diferencias):

        periodo_muestreo = float(
            diferencias.median()
        )

    else:

        periodo_muestreo = 1.0

    if (
        abs(
            periodo_muestreo
            - round(periodo_muestreo)
        )
        < 1e-6
    ):

        periodo_muestreo = float(
            round(periodo_muestreo)
        )

    return {
        "hoja": hoja,
        "fecha": fecha,

        "datos": datos[
            [
                "tiempo_s",
                "hr",
            ]
        ],

        "periodo": periodo_muestreo,

        "inicio": float(
            datos["tiempo_s"].min()
        ),

        "fin": float(
            datos["tiempo_s"].max()
        ),

        "n_muestras": int(
            len(datos)
        ),
    }

