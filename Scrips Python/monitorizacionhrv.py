def formatear_excel(ruta):
    libro = load_workbook(ruta)

    azul = "1F4E78"
    verde = "548235"
    azul_claro = "D9EAF7"
    blanco = "FFFFFF"
    rojo_claro = "FCE4D6"

    borde = Border(
        left=Side(
            style="thin",
            color="A6A6A6",
        ),
        right=Side(
            style="thin",
            color="A6A6A6",
        ),
        top=Side(
            style="thin",
            color="A6A6A6",
        ),
        bottom=Side(
            style="thin",
            color="A6A6A6",
        ),
    )

    for hoja in libro.worksheets:

        hoja.sheet_view.showGridLines = False

        if hoja.title == "CONTROL":
            hoja.freeze_panes = "A2"
        else:
            hoja.freeze_panes = "A3"

        for fila in hoja.iter_rows():

            for celda in fila:

                celda.border = borde

                celda.alignment = Alignment(
                    horizontal="center",
                    vertical="center",
                    wrap_text=True,
                )

        for celda in hoja[1]:

            celda.font = Font(
                bold=True,
                color=blanco,
            )

            celda.fill = PatternFill(
                "solid",
                fgColor=azul,
            )

        if hoja.title != "CONTROL":

            for numero_fila in range(
                1,
                hoja.max_row + 1,
            ):

                valor = hoja.cell(
                    numero_fila,
                    1,
                ).value

                if (
                    isinstance(valor, str)
                    and valor.startswith(
                        "PARTE DE"
                    )
                ):

                    hoja.merge_cells(
                        start_row=numero_fila,
                        start_column=1,
                        end_row=numero_fila,
                        end_column=9,
                    )

                    hoja.cell(
                        numero_fila,
                        1,
                    ).font = Font(
                        bold=True,
                        color=blanco,
                    )

                    hoja.cell(
                        numero_fila,
                        1,
                    ).fill = PatternFill(
                        "solid",
                        fgColor=verde,
                    )

                    for columna in range(
                        1,
                        10,
                    ):

                        hoja.cell(
                            numero_fila + 1,
                            columna,
                        ).font = Font(
                            bold=True
                        )

                        hoja.cell(
                            numero_fila + 1,
                            columna,
                        ).fill = PatternFill(
                            "solid",
                            fgColor=azul_claro,
                        )

        else:

            columna_avisos = None

            for celda in hoja[1]:

                if celda.value == "Avisos":
                    columna_avisos = celda.column
                    break

            if columna_avisos:

                for numero_fila in range(
                    2,
                    hoja.max_row + 1,
                ):

                    if hoja.cell(
                        numero_fila,
                        columna_avisos,
                    ).value:

                        for columna in range(
                            1,
                            hoja.max_column + 1,
                        ):

                            hoja.cell(
                                numero_fila,
                                columna,
                            ).fill = PatternFill(
                                "solid",
                                fgColor=rojo_claro,
                            )

        for numero_columna in range(
            1,
            hoja.max_column + 1,
        ):

            longitudes = [
                (
                    len(
                        str(
                            hoja.cell(
                                numero_fila,
                                numero_columna,
                            ).value
                        )
                    )
                    if (
                        hoja.cell(
                            numero_fila,
                            numero_columna,
                        ).value
                        is not None
                    )
                    else 0
                )
                for numero_fila in range(
                    1,
                    hoja.max_row + 1,
                )
            ]

            anchura = min(
                max(
                    longitudes + [10]
                )
                + 2,
                40,
            )

            hoja.column_dimensions[
                get_column_letter(
                    numero_columna
                )
            ].width = anchura

    libro.save(ruta)


