# ================================================================

def identificar_archivos(
    archivos,
    hoja_rpe,
):
    candidatos_rpe = []
    candidatos_hrv = []

    for archivo in archivos:

        libro = load_workbook(
            archivo,
            read_only=True,
            data_only=True,
        )

        nombres_hojas = libro.sheetnames
        libro.close()

        if hoja_rpe in nombres_hojas:
            candidatos_rpe.append(
                archivo
            )
        else:
            candidatos_hrv.append(
                archivo
            )

    if len(candidatos_rpe) != 1:
        raise ValueError(
            "Debe existir exactamente un Excel "
            f"con una hoja llamada «{hoja_rpe}». "
            f"Encontrados: {candidatos_rpe}"
        )

    if len(candidatos_hrv) != 1:
        raise ValueError(
            "Debe existir exactamente un Excel "
            "de sesiones HRV. "
            f"Encontrados: {candidatos_hrv}"
        )

    return (
        candidatos_hrv[0],
        candidatos_rpe[0],
    )


