def calcular_zonas(
    datos,
    inicio,
    fin,
    hrmax,
    periodo,
    incluir_menores_60,
    recortar_intervalos,
    decimales_minutos,
):
    avisos = []

    if inicio is None or fin is None:
        return (
            None,
            ["Falta el tiempo inicial o final."],
        )

    if fin < inicio:
        return (
            None,
            [
                "El tiempo final es menor "
                "que el inicial."
            ],
        )

    inicio_usado = float(inicio)
    fin_usado = float(fin)

    minimo_registro = float(
        datos["tiempo_s"].min()
    )

    maximo_registro = float(
        datos["tiempo_s"].max()
    )

    if (
        inicio_usado < minimo_registro
        or fin_usado > maximo_registro
    ):

        if not recortar_intervalos:
            return (
                None,
                [
                    "El intervalo queda fuera "
                    "del registro de FC."
                ],
            )

        inicio_usado = max(
            inicio_usado,
            minimo_registro,
        )

        fin_usado = min(
            fin_usado,
            maximo_registro,
        )

        avisos.append(
            "Intervalo recortado al periodo "
            "disponible de FC."
        )

    if fin_usado < inicio_usado:
        return (
            None,
            avisos
            + [
                "El intervalo no se solapa "
                "con el registro de FC."
            ],
        )

    frecuencias = datos.loc[
        (
            datos["tiempo_s"]
            >= inicio_usado - 1e-6
        )
        & (
            datos["tiempo_s"]
            <= fin_usado + 1e-6
        ),
        "hr",
    ].to_numpy(
        dtype=float
    )

    if len(frecuencias) == 0:
        return (
            None,
            avisos
            + [
                "No hay muestras de FC "
                "en el intervalo."
            ],
        )

    umbrales = {
        porcentaje: redondear_umbral(
            hrmax
            * porcentaje
            / 100
        )
        for porcentaje in [
            60,
            70,
            80,
            90,
            100,
            110,
        ]
    }

    if incluir_menores_60:

        mascara_z1 = (
            frecuencias
            <= umbrales[70]
        )

        segundos_bajo_60 = 0

    else:

        mascara_z1 = (
            (
                frecuencias
                >= umbrales[60]
            )
            & (
                frecuencias
                <= umbrales[70]
            )
        )

        segundos_bajo_60 = (
            float(
                np.sum(
                    frecuencias
                    < umbrales[60]
                )
            )
            * periodo
        )

    mascaras = [
        mascara_z1,

        (
            (
                frecuencias
                >= umbrales[70]
            )
            & (
                frecuencias
                < umbrales[80]
            )
        ),

        (
            (
                frecuencias
                >= umbrales[80]
            )
            & (
                frecuencias
                < umbrales[90]
            )
        ),

        (
            (
                frecuencias
                >= umbrales[90]
            )
            & (
                frecuencias
                < umbrales[100]
            )
        ),

        (
            (
                frecuencias
                >= umbrales[100]
            )
            & (
                frecuencias
                < umbrales[110]
            )
        ),

        frecuencias >= umbrales[110],
    ]

    segundos = [
        float(
            np.sum(mascara)
        )
        * periodo
        for mascara in mascaras
    ]

    segundos_limpios = [
        (
            int(round(valor))
            if (
                abs(
                    valor
                    - round(valor)
                )
                < 1e-8
            )
            else round(valor, 3)
        )
        for valor in segundos
    ]

    minutos = [
        round(
            valor / 60,
            decimales_minutos,
        )
        for valor in segundos
    ]

    return (
        {
            "umbrales": umbrales,
            "segundos": segundos_limpios,
            "minutos": minutos,
            "inicio_usado": inicio_usado,
            "fin_usado": fin_usado,
            "muestras": len(frecuencias),
            "bajo60": segundos_bajo_60,
        },
        avisos,
    )


