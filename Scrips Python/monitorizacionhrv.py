def generar_excel(
    archivo_hrv,
    archivo_rpe,
    sujeto,
    hoja_rpe,
    incluir_menores_60,
    recortar_intervalos,
    decimales_minutos,
    modo_emparejamiento,
    permitir_fallback,
    nombre_salida,
):
    informacion_rpe = leer_valoracion_rpe(
        ruta=archivo_rpe,
        hoja_rpe=hoja_rpe,
        sujeto=sujeto,
    )

    libro_hrv = pd.ExcelFile(
        archivo_hrv
    )

    sesiones_hrv = [
        leer_hoja_hrv(
            ruta=archivo_hrv,
            hoja=nombre_hoja,
        )
        for nombre_hoja
        in libro_hrv.sheet_names
    ]

    zonas = [
        "Z1",
        "Z2",
        "Z3",
        "Z4",
        "Z5",
        "Z6",
    ]

    rangos = [
        "60–70%",
        "70–80%",
        "80–90%",
        "90–100%",
        "100–110%",
        ">110%",
    ]

    control = []
    hojas_usadas = set()
    nombres_generados = set()

    if not nombre_salida.lower().endswith(
        ".xlsx"
    ):
        nombre_salida += ".xlsx"

    with pd.ExcelWriter(
        nombre_salida,
        engine="openpyxl",
    ) as escritor:

        sesiones_ordenadas = sorted(
            informacion_rpe["sesiones"],
            key=lambda elemento: elemento["numero"],
        )

        for sesion_rpe in sesiones_ordenadas:

            (
                sesion_hrv,
                metodo,
                aviso_emparejamiento,
            ) = emparejar_sesion(
                sesion_rpe=sesion_rpe,
                sesiones_hrv=sesiones_hrv,
                hojas_usadas=hojas_usadas,
                modo=modo_emparejamiento,
                permitir_fallback=permitir_fallback,
            )

            if sesion_hrv is None:

                control.append(
                    {
                        "Sesión": sesion_rpe["numero"],
                        "Fecha RPE": sesion_rpe["fecha"],
                        "Hoja HRV": "",
                        "Fecha HRV": "",
                        "Método": metodo,
                        "Parte": "",
                        "Inicio solicitado": "",
                        "Fin solicitado": "",
                        "Inicio usado": "",
                        "Fin usado": "",
                        "Muestras": "",
                        "Segundos Z1–Z6": "",
                        "Segundos <60%": "",
                        "Avisos": aviso_emparejamiento,
                    }
                )

                continue

            hojas_usadas.add(
                sesion_hrv["hoja"]
            )

            nombre_hoja = nombre_hoja_seguro(
                nombre=(
                    f"S{sesion_rpe['numero']}_"
                    f"{sesion_hrv['hoja']}"
                ),
                existentes=nombres_generados,
            )

            nombres_generados.add(
                nombre_hoja
            )

            fila_inicio = 0

            for parte in [
                "FUERZA",
                "FUNCIONAL",
                "RESISTENCIA",
            ]:

                informacion_parte = (
                    sesion_rpe[parte]
                )

                resultado_50, avisos_50 = calcular_zonas(
                    datos=sesion_hrv["datos"],
                    inicio=informacion_parte["inicio"],
                    fin=informacion_parte["fin"],
                    hrmax=informacion_rpe["hrmax50"],
                    periodo=sesion_hrv["periodo"],
                    incluir_menores_60=incluir_menores_60,
                    recortar_intervalos=recortar_intervalos,
                    decimales_minutos=decimales_minutos,
                )

                resultado_75, avisos_75 = calcular_zonas(
                    datos=sesion_hrv["datos"],
                    inicio=informacion_parte["inicio"],
                    fin=informacion_parte["fin"],
                    hrmax=informacion_rpe["hrmax75"],
                    periodo=sesion_hrv["periodo"],
                    incluir_menores_60=incluir_menores_60,
                    recortar_intervalos=recortar_intervalos,
                    decimales_minutos=decimales_minutos,
                )

                avisos = list(
                    dict.fromkeys(
                        [
                            aviso
                            for aviso in (
                                [aviso_emparejamiento]
                                + avisos_50
                                + avisos_75
                            )
                            if aviso
                        ]
                    )
                )

                if (
                    resultado_50 is None
                    or resultado_75 is None
                ):

                    tabla = pd.DataFrame(
                        {
                            "Aviso": [
                                " | ".join(
                                    avisos
                                )
                            ]
                        }
                    )

                else:

                    limites_50 = [
                        resultado_50["umbrales"][70],
                        resultado_50["umbrales"][80],
                        resultado_50["umbrales"][90],
                        resultado_50["umbrales"][100],
                        resultado_50["umbrales"][110],
                        resultado_50["umbrales"][110],
                    ]

                    limites_75 = [
                        resultado_75["umbrales"][70],
                        resultado_75["umbrales"][80],
                        resultado_75["umbrales"][90],
                        resultado_75["umbrales"][100],
                        resultado_75["umbrales"][110],
                        resultado_75["umbrales"][110],
                    ]

                    tabla = pd.DataFrame(
                        {
                            "Zona": zonas,
                            "%": rangos,

                            "HR 0.5": limites_50,
                            "segundos 0.5": resultado_50["segundos"],
                            "minutos 0.5": resultado_50["minutos"],

                            "HR 0.75": limites_75,
                            "segundos 0.75": resultado_75["segundos"],
                            "minutos 0.75": resultado_75["minutos"],

                            f"RPE {parte}": [
                                informacion_parte["rpe"],
                                "",
                                "",
                                "",
                                "",
                                "",
                            ],
                        }
                    )

                    control.append(
                        {
                            "Sesión": sesion_rpe["numero"],
                            "Fecha RPE": sesion_rpe["fecha"],
                            "Hoja HRV": sesion_hrv["hoja"],
                            "Fecha HRV": sesion_hrv["fecha"],
                            "Método": metodo,
                            "Parte": parte,

                            "Inicio solicitado": segundos_a_hms(
                                informacion_parte["inicio"]
                            ),

                            "Fin solicitado": segundos_a_hms(
                                informacion_parte["fin"]
                            ),

                            "Inicio usado": segundos_a_hms(
                                resultado_50["inicio_usado"]
                            ),

                            "Fin usado": segundos_a_hms(
                                resultado_50["fin_usado"]
                            ),

                            "Muestras": resultado_50["muestras"],

                            "Segundos Z1–Z6": sum(
                                resultado_50["segundos"]
                            ),

                            "Segundos <60%": resultado_50["bajo60"],

                            "Avisos": " | ".join(
                                avisos
                            ),
                        }
                    )

                pd.DataFrame(
                    [
                        [
                            f"PARTE DE {parte}"
                        ]
                    ]
                ).to_excel(
                    escritor,
                    sheet_name=nombre_hoja,
                    startrow=fila_inicio,
                    index=False,
                    header=False,
                )

                tabla.to_excel(
                    escritor,
                    sheet_name=nombre_hoja,
                    startrow=fila_inicio + 1,
                    index=False,
                )

                fila_inicio += (
                    len(tabla)
                    + 4
                )

        pd.DataFrame(
            control
        ).to_excel(
            escritor,
            sheet_name="CONTROL",
            index=False,
        )

    formatear_excel(
        nombre_salida
    )

    return (
        nombre_salida,
        control,
    )


