def normalizar(valor):
    """
    Normaliza encabezados eliminando tildes, espacios y símbolos.
    """
    if valor is None:
        return ""

    valor = unicodedata.normalize(
        "NFKD",
        str(valor),
    )

    valor = "".join(
        caracter
        for caracter in valor
        if not unicodedata.combining(caracter)
    )

    return re.sub(
        r"[^A-Z0-9]",
        "",
        valor.upper(),
    )


def esta_vacio(valor):
    try:
        return valor is None or pd.isna(valor)
    except Exception:
        return valor is None


def convertir_fecha(valor):
    """
    Convierte fechas de Excel, pandas o texto a datetime.date.
    """
    if esta_vacio(valor):
        return None

    if isinstance(valor, pd.Timestamp):
        return valor.date()

    if isinstance(valor, datetime):
        return valor.date()

    if isinstance(valor, date):
        return valor

    if isinstance(
        valor,
        (
            int,
            float,
            np.integer,
            np.floating,
        ),
    ):
        return (
            pd.Timestamp("1899-12-30")
            + pd.to_timedelta(
                float(valor),
                unit="D",
            )
        ).date()

    valor = pd.to_datetime(
        valor,
        dayfirst=True,
        errors="coerce",
    )

    if pd.isna(valor):
        return None

    return valor.date()


def convertir_a_segundos(valor):
    """
    Convierte una hora o duración de Excel a segundos.
    """
    if esta_vacio(valor):
        return None

    if isinstance(valor, pd.Timedelta):
        return float(valor.total_seconds())

    if isinstance(valor, datetime):
        return (
            valor.hour * 3600
            + valor.minute * 60
            + valor.second
            + valor.microsecond / 1e6
        )

    if isinstance(valor, time):
        return (
            valor.hour * 3600
            + valor.minute * 60
            + valor.second
            + valor.microsecond / 1e6
        )

    if isinstance(
        valor,
        (
            int,
            float,
            np.integer,
            np.floating,
        ),
    ):
        valor = float(valor)

        # Excel almacena las horas como fracciones de un día.
        if abs(valor) < 2:
            return valor * 86400

        return valor

    texto = str(valor).strip().replace(",", ".")

    if ":" in texto:

        partes = [
            float(elemento)
            for elemento in texto.split(":")
        ]

        if len(partes) == 3:
            return (
                partes[0] * 3600
                + partes[1] * 60
                + partes[2]
            )

        if len(partes) == 2:
            return (
                partes[0] * 60
                + partes[1]
            )

    valor = float(texto)

    if abs(valor) < 2:
        return valor * 86400

    return valor


def redondear_umbral(valor):
    """
    Aplica redondeo convencional:
    148.5 se transforma en 149.
    """
    return int(
        Decimal(
            str(float(valor))
        ).quantize(
            Decimal("1"),
            rounding=ROUND_HALF_UP,
        )
    )


def segundos_a_hms(valor):
    """
    Convierte segundos a HH:MM:SS.
    """
    if valor is None or pd.isna(valor):
        return ""

    valor = max(
        0,
        int(round(float(valor))),
    )

    horas, resto = divmod(
        valor,
        3600,
    )

    minutos, segundos = divmod(
        resto,
        60,
    )

    return (
        f"{horas:02d}:"
        f"{minutos:02d}:"
        f"{segundos:02d}"
    )


def obtener_valor(
    fila,
    columnas,
    *nombres,
):
    """
    Busca una variable en la fila RPE aceptando varias formas
    posibles de escribir su encabezado.
    """
    for nombre in nombres:

        columna_original = columnas.get(
            normalizar(nombre)
        )

        if columna_original is not None:

            valor = fila[
                columna_original
            ]

            if not esta_vacio(valor):
                return valor

    return None


def nombre_hoja_seguro(
    nombre,
    existentes,
):
    """
    Genera un nombre de hoja válido y no repetido.
    """
    nombre = re.sub(
        r"[\[\]\*\?/\\:]",
        "_",
        str(nombre),
    )

    nombre = nombre[:31] or "Sesion"
    nombre_base = nombre

    contador = 2

    while nombre in existentes:

        sufijo = f"_{contador}"

        nombre = (
            nombre_base[
                :31 - len(sufijo)
            ]
            + sufijo
        )

        contador += 1

    return nombre


